async function main() {
  console.log('Đang chạy seed dữ liệu Ingredient...');
  
  for (const item of INGREDIENTS) {
    await prisma.ingredient.upsert({
      where: { id: item.id },
      update: {
        icon: item.icon,
        badge: item.badge,
        title: item.title as any,
        riskLabel: item.riskLabel as any,
        shortContent: item.shortContent as any,
        pets: item.pets as any,
        details: item.details as any,
        benefits: item.benefits as any,
      },
      create: {
        id: item.id,
        icon: item.icon,
        badge: item.badge,
        title: item.title as any,
        riskLabel: item.riskLabel as any,
        shortContent: item.shortContent as any,
        pets: item.pets as any,
        details: item.details ? (item.details as any) : undefined,
        benefits: item.benefits ? (item.benefits as any) : undefined,
      },
    });
  }

  console.log(`Đã seed thành công ${INGREDIENTS.length} mục Ingredient!`);
}

main()
